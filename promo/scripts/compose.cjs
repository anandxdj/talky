#!/usr/bin/env node
/**
 * Writes the two HyperFrames compositions from one template:
 *   promo/hf/index.html     16:9  1920×1080 @60
 *   promo/hf/vertical.html  9:16  1080×1920 @60
 * The beat timings below are the film's single source of truth (see promo/STORYBOARD.md);
 * film.js reads them back from the media's data-start attributes.
 */
const fs = require('node:fs')
const path = require('node:path')

const HF = path.resolve(__dirname, '..', 'hf')
const BUILD = path.join(HF, 'build')

// Seconds. Clip starts are the moment each real UI performance begins.
const T = {
  duration: 39,
  hourly: 5.75, // bars grow (1.5s)
  heat: 9.15, // heatmap lights up (1.6s)
  queue: 12.9, // live queue interaction (open → type → Send), ~7.6s file
  queueDur: 7.45,
  words: 21.5, // words-per-day line draws (1.6s)
  dumbbell: 24.0, // You-vs-Talky dots slide in (1.3s)
  lengths: 26.3, // message-length bars (1.1s)
  control: 28.7, // Pause replies → banner, then theme flip
  controlDur: 4.35,
  end: 33.2, // end card begins
}

const MARK = (id) => `<svg viewBox="0 0 28 28" aria-hidden="true">
          <rect width="28" height="28" rx="8" fill="#F0EFEC"/>
          <g id="${id}-glyph"><path d="M8 10.5h12M8 14h8M8 17.5h5" stroke="#141413" stroke-width="2.2" stroke-linecap="round"/>
          <circle id="${id}-dot" cx="20" cy="18" r="2.5" fill="#EB6834"/></g>
        </svg>`

const words = (text, accent = []) =>
  text
    .split(' ')
    .map((w, i, a) => `<span class="w${accent.includes(i) ? ' accent' : ''}">${w}${i < a.length - 1 ? ' ' : ''}</span>`)
    .join('')
const lines = (rows) => rows.map(([t, acc]) => `<span class="ln">${words(t, acc)}</span>`).join('<br/>')

const ARROW = `<svg class="arrow" viewBox="0 0 26 34"><path d="M3 2 L3 27 L9.2 21.2 L13.4 31 L17.6 29.2 L13.5 19.6 L22 19.6 Z" fill="#141413" stroke="#fff" stroke-width="2" stroke-linejoin="round"/></svg>`

function compose(fmt) {
  const tall = fmt === 'tall'
  const W = tall ? 1080 : 1920
  const H = tall ? 1920 : 1080
  const A = `assets/${fmt}`
  const cursor = (id) =>
    tall ? `<div id="${id}" class="cursor touch"><div class="arrow"></div></div>` : `<div id="${id}" class="cursor">${ARROW}</div>`

  // Captions: wide = one pill near the bottom; tall = stacked lines in the top caption band.
  const cap = (id, rowsWide, rowsTall) =>
    `<div id="${id}" class="cap">
        <div class="pill">${tall ? lines(rowsTall) : lines(rowsWide)}</div>
      </div>`

  const css = tall
    ? `
      #mark { left: 430px; top: 640px; width: 220px; height: 220px; }
      #hook-title { top: 930px; font-size: 96px; }
      .cap { top: 175px; }
      #stage { clip-path: inset(480px 0 0 0 round 36px 36px 0 0); }
      .cap .pill { font-size: 70px; line-height: 1.08; padding: 30px 54px 36px; border-radius: 48px; }
      #end-lockup { gap: 34px; }
      #end-mark { width: 170px; height: 170px; }
      #end-word { font-size: 190px; }
      #end-line { font-size: 74px; margin-top: 70px; text-align: center; line-height: 1.12; }
      #end-url { font-size: 38px; margin-top: 56px; padding: 18px 36px; }
      #end { padding-bottom: 380px; }`
    : `
      #mark { left: 870px; top: 250px; width: 180px; height: 180px; }
      #hook-title { top: 520px; font-size: 92px; }
      .cap { bottom: 64px; }
      .cap .pill { font-size: 50px; padding: 20px 42px 24px; }
      #end-lockup { gap: 30px; }
      #end-mark { width: 132px; height: 132px; }
      #end-word { font-size: 150px; }
      #end-line { font-size: 62px; margin-top: 54px; }
      #end-url { font-size: 32px; margin-top: 40px; padding: 14px 30px; }`

  const hookTitle = tall
    ? lines([['Your WhatsApp,', []], ['answered in', []], ['your voice.', [0, 1]]])
    : lines([['Your WhatsApp, answered in your voice.', [4, 5]]])
  const endLine = tall
    ? lines([['Local-first.', []], ['Private. Yours.', [1]]])
    : words('Local-first. Private. Yours.', [2])

  const v = (id, file, start, dur) =>
    `<video id="${id}" class="clip" src="${A}/${file}" muted playsinline data-start="${start}" data-duration="${dur}"></video>`

  return `<!doctype html>
<html lang="en">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=${W}, height=${H}" />
    <title>Talky — ${tall ? '9:16' : '16:9'}</title>
    <!-- Generated by promo/scripts/compose.cjs — edit timings there, motion in film.js. -->
    <script src="vendor/gsap.min.js"></script>
    <script src="layout.js"></script>
    <link rel="stylesheet" href="film.css" />
    <style>
      html, body { width: ${W}px; height: ${H}px; }
      #root { width: ${W}px; height: ${H}px; }${css}
    </style>
  </head>
  <body>
    <div id="root" data-composition-id="main" data-format="${fmt}" data-start="0" data-duration="${T.duration}"
      data-width="${W}" data-height="${H}" data-fps="60" data-motion-blur="on" data-motion-blur-shutter="200">
      <div id="bg" class="layer" data-motion-blur="off"></div>

      <!-- 1 · hook -->
      <div id="hook" class="layer">
        <div id="mark">${MARK('mark')}</div>
        <h1 id="hook-title">${hookTitle}</h1>
      </div>
      <div id="morph" class="layer"></div>

      <!-- product stage (tall: its own band under the captions) -->
      <div id="stage" class="layer">
      <!-- 2 · overview: plate with charts at 0, real reveal clips on top -->
      <div id="w-overview" class="world">
        <img class="plate" src="${A}/overview-start.png" alt="" />
        ${v('v-hourly', 'overview-hourly.mp4', T.hourly, (T.queue - T.hourly).toFixed(2))}
        ${v('v-heat', 'overview-heat.mp4', T.heat, (T.queue - T.heat).toFixed(2))}
      </div>

      <!-- 3 · live queue: recorded interaction -->
      <div id="w-queue" class="world">
        ${v('v-queue', 'queue.mp4', T.queue, T.queueDur)}
        ${cursor('cur-queue')}
      </div>

      <!-- 4 · voice fingerprint -->
      <div id="w-voice" class="world">
        <img class="plate" src="${A}/voice-start.png" alt="" />
        ${v('v-words', 'voice-words.mp4', T.words, (T.control - T.words).toFixed(2))}
        ${v('v-dumbbell', 'voice-dumbbell.mp4', T.dumbbell, (T.control - T.dumbbell).toFixed(2))}
        ${v('v-lengths', 'voice-lengths.mp4', T.lengths, (T.control - T.lengths).toFixed(2))}
      </div>

      <!-- 5 · control: Pause replies, then the theme flip -->
      <div id="w-control" class="world">
        ${v('v-control', 'control.mp4', T.control, T.controlDur)}
        <img id="control-dark" class="still" src="${A}/control-dark.png" alt="" />
        ${cursor('cur-control')}
      </div>

      </div>
      <div id="flash" class="layer" data-motion-blur="off"></div>

      ${cap('cap-hourly', [['See every reply, hour by hour.', [1, 2]]], [['See every reply,', [1, 2]], ['hour by hour.', []]])}
      ${cap('cap-queue', [['Step in whenever you want.', [0, 1]]], [['Step in', [0, 1]], ['whenever you want.', []]])}
      ${cap('cap-voice', [['Sounds like you.', [2]]], [['Sounds like you.', [2]]])}
      ${cap('cap-control', [['One switch. Total control.', [0, 1]]], [['One switch.', [0, 1]], ['Total control.', []]])}

      <!-- 6 · end card -->
      <div id="end" class="layer" data-at="${T.end}">
        <div id="end-lockup">
          <div id="end-mark">${MARK('end-mark')}</div>
          <div id="end-word">talky</div>
        </div>
        <div id="end-line">${endLine}</div>
        <div id="end-url">github.com/anandxdj/talky</div>
      </div>
    </div>
    <script src="film.js"></script>
  </body>
</html>
`
}

/**
 * Each cut is its own HyperFrames project (one root index.html per project):
 *   promo/hf/build/wide/   promo/hf/build/tall/
 * Shared source (film.js, film.css, vendor/) is copied in; captured media is hard-linked.
 */
function linkTree(src, dst) {
  fs.mkdirSync(dst, { recursive: true })
  for (const name of fs.readdirSync(src)) {
    const a = path.join(src, name)
    const b = path.join(dst, name)
    if (fs.statSync(a).isDirectory()) linkTree(a, b)
    else {
      fs.rmSync(b, { force: true })
      try {
        fs.linkSync(a, b)
      } catch {
        fs.copyFileSync(a, b)
      }
    }
  }
}
for (const fmt of ['wide', 'tall']) {
  const layout = path.join(HF, `layout-${fmt}.js`)
  if (!fs.existsSync(layout)) {
    console.warn(`skip ${fmt}: run the capture first (missing ${path.relative(process.cwd(), layout)})`)
    continue
  }
  const dir = path.join(BUILD, fmt)
  fs.rmSync(dir, { recursive: true, force: true })
  fs.mkdirSync(dir, { recursive: true })
  fs.writeFileSync(path.join(dir, 'index.html'), compose(fmt))
  for (const f of ['film.js', 'film.css', 'hyperframes.json']) fs.copyFileSync(path.join(HF, f), path.join(dir, f))
  fs.writeFileSync(path.join(dir, 'meta.json'), JSON.stringify({ id: `talky-promo-${fmt}`, name: `Talky promo (${fmt === 'wide' ? '16:9' : '9:16'})` }, null, 2))
  fs.copyFileSync(layout, path.join(dir, 'layout.js'))
  linkTree(path.join(HF, 'vendor'), path.join(dir, 'vendor'))
  linkTree(path.join(HF, 'assets', fmt), path.join(dir, 'assets', fmt))
  linkTree(path.join(HF, 'assets', 'fonts'), path.join(dir, 'assets', 'fonts'))
  console.log(`wrote ${path.relative(process.cwd(), dir)}/index.html`)
}
